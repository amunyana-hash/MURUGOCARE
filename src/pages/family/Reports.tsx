import { useMemo, useState } from 'react';
import { Link } from 'react-router-dom';
import { CalendarDays, Download, FileImage, Image as ImageIcon, Search, Video } from 'lucide-react';
import { useAuth } from '../../lib/auth';
import { useI18n } from '../../lib/i18n';
import { usePrefs } from '../../lib/prefs';
import { useRows } from '../../lib/hooks';
import { familyNav } from '../../lib/nav';
import { DashboardShell } from '../../components/layout';
import {
  Badge,
  EmptyState,
  KeyValue,
  Modal,
  PillTabs,
  SectionHeader,
  StatusBadge,
  TextInput,
} from '../../components/ui';
import type { CareReport, FamilyMember, Property } from '../../lib/types';
import { formatDate } from '../../lib/format';

type Filter = 'all' | 'inspection' | 'companionship' | 'maintenance' | 'delivery';

export default function FamilyReports() {
  const { profile } = useAuth();
  const { t } = useI18n();
  const { toast } = usePrefs();
  const ownerId = profile?.id ?? '__none__';

  const { rows: reports } = useRows<CareReport>('care_reports', {
    where: { owner_id: ownerId },
    order: { column: 'created_at', ascending: false },
  });
  const { rows: properties } = useRows<Property>('properties', { where: { owner_id: ownerId } });
  const { rows: relatives } = useRows<FamilyMember>('family_members', { where: { owner_id: ownerId } });

  const [filter, setFilter] = useState<Filter>('all');
  const [query, setQuery] = useState('');
  const [active, setActive] = useState<CareReport | null>(null);

  const nav = familyNav(t as never);

  const counts = useMemo(() => {
    const base: Record<Filter, number> = { all: reports.length, inspection: 0, companionship: 0, maintenance: 0, delivery: 0 };
    reports.forEach((r) => {
      if (r.type in base) base[r.type] += 1;
    });
    return base;
  }, [reports]);

  const visible = useMemo(() => {
    const q = query.trim().toLowerCase();
    return reports.filter((r) => {
      if (filter !== 'all' && r.type !== filter) return false;
      if (!q) return true;
      return r.title.toLowerCase().includes(q) || r.summary.toLowerCase().includes(q) || r.author_name.toLowerCase().includes(q);
    });
  }, [reports, filter, query]);

  const propertyName = (id?: string | null) => properties.find((p) => p.id === id)?.name;
  const relativeName = (id?: string | null) => relatives.find((r) => r.id === id)?.full_name;

  function download(r: CareReport) {
    const lines = [
      'URUGOCARE — COMPLETION REPORT',
      '==============================',
      `Title: ${r.title}`,
      `Type: ${r.type}`,
      `Date: ${r.date}`,
      `Author: ${r.author_name}`,
      r.booking_ref ? `Booking: ${r.booking_ref}` : '',
      propertyName(r.property_id) ? `Property: ${propertyName(r.property_id)}` : '',
      relativeName(r.family_member_id) ? `Relative: ${relativeName(r.family_member_id)}` : '',
      '',
      'Summary',
      '-------',
      r.summary,
      '',
      'Media',
      '-----',
      ...(r.media.length ? r.media.map((m) => `- [${m.kind}] ${m.label}`) : ['- No media attached']),
      '',
      'Generated by URUGOCARE — Bugesera District, Rwanda',
    ].filter(Boolean);
    const blob = new Blob([lines.join('\n')], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${r.title.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}-${r.date}.txt`;
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
    toast('Report downloaded', r.title);
  }

  return (
    <DashboardShell
      title={t('family.reports', 'Reports')}
      subtitle="Photo, video and written evidence from every visit to your property or relative."
      items={nav}
      accent={t('family.diasporaBadge', 'Diaspora')}
    >
      <div className="grid gap-4 sm:grid-cols-4">
        {[
          { label: 'Total reports', value: reports.length },
          { label: 'Photos', value: reports.reduce((s, r) => s + r.media.filter((m) => m.kind === 'photo').length, 0) },
          { label: 'Videos', value: reports.reduce((s, r) => s + r.media.filter((m) => m.kind === 'video').length, 0) },
          { label: 'Reviewed', value: reports.filter((r) => r.status === 'reviewed').length },
        ].map((s) => (
          <div key={s.label} className="card card-pad">
            <p className="kicker">{s.label}</p>
            <p className="stat-value mt-2">{s.value}</p>
          </div>
        ))}
      </div>

      <div className="mt-6 flex flex-wrap items-center justify-between gap-3">
        <PillTabs<Filter>
          value={filter}
          onChange={setFilter}
          tabs={[
            { key: 'all', label: t('common.all', 'All'), count: counts.all },
            { key: 'inspection', label: 'Inspection', count: counts.inspection },
            { key: 'companionship', label: 'Companionship', count: counts.companionship },
            { key: 'maintenance', label: 'Maintenance', count: counts.maintenance },
            { key: 'delivery', label: 'Delivery', count: counts.delivery },
          ]}
        />
        <div className="relative w-full max-w-xs">
          <Search className="pointer-events-none absolute left-3 top-1/2 h-4 w-4 -translate-y-1/2 text-forest-400" />
          <TextInput
            className="pl-9"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder={t('common.search', 'Search reports')}
            aria-label="Search reports"
          />
        </div>
      </div>

      {visible.length === 0 ? (
        <div className="mt-6">
          <EmptyState
            icon="FileImage"
            title={reports.length ? 'No report matches' : 'No reports yet'}
            body={
              reports.length
                ? 'Try another filter or search term.'
                : 'Once a provider completes a visit for your property or relative, the coordinator uploads photos and a written report here.'
            }
            action={
              <Link to="/family/requests" className="btn-primary btn-sm">
                Request a service
              </Link>
            }
          />
        </div>
      ) : (
        <div className="mt-5 space-y-3">
          {visible.map((r) => (
            <article key={r.id} className="card card-pad">
              <div className="flex flex-wrap items-start justify-between gap-3">
                <div className="min-w-0">
                  <div className="flex flex-wrap items-center gap-2">
                    <Badge tone="gold">{r.type}</Badge>
                    <StatusBadge status={r.status} />
                    {r.booking_ref && <span className="text-[11px] font-semibold text-forest-500">{r.booking_ref}</span>}
                  </div>
                  <h3 className="mt-1.5 font-display text-lg text-forest-900">{r.title}</h3>
                  <p className="mt-0.5 flex flex-wrap items-center gap-x-3 gap-y-1 text-[11.5px] text-forest-500">
                    <span className="flex items-center gap-1">
                      <CalendarDays className="h-3 w-3" /> {formatDate(r.date)}
                    </span>
                    <span>By {r.author_name}</span>
                    {propertyName(r.property_id) && <span>{propertyName(r.property_id)}</span>}
                    {relativeName(r.family_member_id) && <span>{relativeName(r.family_member_id)}</span>}
                  </p>
                </div>
                <div className="flex gap-1.5">
                  <button type="button" className="btn-outline btn-sm" onClick={() => setActive(r)}>
                    Open report
                  </button>
                  <button type="button" className="btn-ghost btn-sm" aria-label="Download report" onClick={() => download(r)}>
                    <Download className="h-4 w-4" />
                  </button>
                </div>
              </div>

              <p className="mt-3 text-[12.5px] leading-relaxed text-forest-700">{r.summary}</p>

              {r.media.length > 0 && (
                <div className="mt-3 flex flex-wrap gap-2">
                  {r.media.map((m, i) => (
                    <span
                      key={`${r.id}-${i}`}
                      className="flex items-center gap-1.5 rounded-lg border border-forest-100 bg-forest-50/60 px-2.5 py-1.5 text-[11px] font-medium text-forest-700"
                    >
                      {m.kind === 'photo' ? <ImageIcon className="h-3.5 w-3.5" /> : <Video className="h-3.5 w-3.5" />}
                      {m.label}
                    </span>
                  ))}
                </div>
              )}
            </article>
          ))}
        </div>
      )}

      <div className="mt-8 card card-pad">
        <SectionHeader
          title="Report standard"
          subtitle="Every URUGOCARE completion report follows the same structure so nothing is missed."
        />
        <div className="grid gap-3 sm:grid-cols-4">
          {[
            { title: 'Arrival & identity', body: 'Provider check-in time and on-site verification.' },
            { title: 'Work performed', body: 'Exact tasks completed with before/after photos.' },
            { title: 'Issues found', body: 'Anything that needs follow-up, quoted separately.' },
            { title: 'Coordinator sign-off', body: 'Reviewed by the Bugesera coordinator before release.' },
          ].map((c) => (
            <div key={c.title} className="rounded-xl border border-forest-100 p-3.5">
              <FileImage className="h-4 w-4 text-forest-600" />
              <p className="mt-2 text-[13px] font-semibold text-forest-900">{c.title}</p>
              <p className="mt-0.5 text-[11.5px] leading-relaxed text-forest-600">{c.body}</p>
            </div>
          ))}
        </div>
      </div>

      <Modal
        open={Boolean(active)}
        onClose={() => setActive(null)}
        title={active?.title ?? 'Report'}
        description={active ? `${active.type} · ${formatDate(active.date)}` : undefined}
        wide
        footer={
          <>
            <button type="button" className="btn-ghost btn-sm" onClick={() => setActive(null)}>
              {t('common.close', 'Close')}
            </button>
            {active && (
              <button type="button" className="btn-primary btn-sm" onClick={() => download(active)}>
                <Download className="h-4 w-4" /> Download
              </button>
            )}
          </>
        }
      >
        {active && (
          <div className="space-y-4">
            <div className="grid gap-2 sm:grid-cols-3">
              <KeyValue label="Type" value={active.type} />
              <KeyValue label="Date" value={formatDate(active.date)} />
              <KeyValue label="Author" value={active.author_name} />
              {active.booking_ref && <KeyValue label="Booking" value={active.booking_ref} />}
              {propertyName(active.property_id) && (
                <KeyValue label="Property" value={propertyName(active.property_id)} />
              )}
              {relativeName(active.family_member_id) && (
                <KeyValue label="Relative" value={relativeName(active.family_member_id)} />
              )}
            </div>
            <div>
              <p className="kicker mb-1.5">Summary</p>
              <p className="text-[13px] leading-relaxed text-forest-700">{active.summary}</p>
            </div>
            <div>
              <p className="kicker mb-1.5">Media ({active.media.length})</p>
              {active.media.length === 0 ? (
                <p className="text-[12.5px] text-forest-500">No media attached to this report.</p>
              ) : (
                <ul className="grid gap-2 sm:grid-cols-2">
                  {active.media.map((m, i) => (
                    <li
                      key={`${active.id}-m-${i}`}
                      className="flex items-center gap-2 rounded-xl border border-forest-100 px-3 py-2.5"
                    >
                      <span className="flex h-8 w-8 items-center justify-center rounded-lg bg-forest-50 text-forest-600">
                        {m.kind === 'photo' ? <ImageIcon className="h-4 w-4" /> : <Video className="h-4 w-4" />}
                      </span>
                      <span className="min-w-0">
                        <span className="block truncate text-[12.5px] font-semibold text-forest-900">{m.label}</span>
                        <span className="block text-[11px] text-forest-500">
                          {m.kind === 'photo' ? 'Photograph' : 'Video clip'}
                        </span>
                      </span>
                    </li>
                  ))}
                </ul>
              )}
            </div>
            <div className="rounded-xl bg-forest-50/70 px-4 py-3">
              <p className="text-[11.5px] leading-relaxed text-forest-700">
                Media files are stored securely and shared only with you. Ask the coordinator for full-resolution copies
                or an original video file if you need them for records.
              </p>
            </div>
          </div>
        )}
      </Modal>
    </DashboardShell>
  );
}
