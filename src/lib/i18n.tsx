interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string, fallback?: string) => string;
  categoryName: (c: { name_en: string; name_fr: string; name_rw: string }) => string;
  categoryTagline: (c: { tagline_en: string; tagline_fr: string; tagline_rw: string }) => string;
  categoryDescription: (c: { description_en: string; description_fr: string; description_rw: string }) => string;
  locale: string;
}

const I18nContext = createContext<I18nValue | null>(null);
const LANG_KEY = 'urugocare:lang';

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    if (typeof window === 'undefined') return 'en';
    const stored = window.localStorage.getItem(LANG_KEY) as Lang | null;
    if (stored === 'en' || stored === 'fr' || stored === 'rw') return stored;
    const nav = window.navigator.language.slice(0, 2);
    if (nav === 'fr') return 'fr';
    if (nav === 'rw') return 'rw';
    return 'en';
  });

  useEffect(() => {
    document.documentElement.lang = lang === 'rw' ? 'rw' : lang;
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    try {
      window.localStorage.setItem(LANG_KEY, next);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo<I18nValue>(() => {
    const idx = lang === 'fr' ? 1 : lang === 'rw' ? 2 : 0;
    const t = (key: string, fallback?: string) => {
      const entry = dict[key];
      if (!entry) return fallback ?? key;
      return entry[idx] || entry[0] || fallback || key;
    };
    return {
      lang,
      setLang,
      t,
      locale: lang === 'fr' ? 'fr-FR' : 'en-GB',
      categoryName: (c) => (lang === 'fr' ? c.name_fr : lang === 'rw' ? c.name_rw : c.name_en),
      categoryTagline: (c) => (lang === 'fr' ? c.tagline_fr : lang === 'rw' ? c.tagline_rw : c.tagline_en),
      categoryDescription: (c) =>
        lang === 'fr' ? c.description_fr : lang === 'rw' ? c.description_rw : c.description_en,
    };
  }, [lang, setLang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}

